#!/usr/bin/env python3
"""Generate versioned contract artifacts from the Pydantic models, and detect drift.

`write` updates contracts/generated/openapi.json and packages/api-client/src/generated.ts. `check`
generates to memory and compares. Generation builds the pure app, so it opens nothing and needs no
key. A TypeScript type does not validate JSON, so every generated `parse` function checks at runtime.

Exit codes: 0 current or written, 1 drift, 2 the prepared Python environment is missing.
"""
from __future__ import annotations

import json
import re
import subprocess
import sys
from collections.abc import Iterable, Mapping
from pathlib import Path

from harness_lib import project_root, reduced_env

OPENAPI = Path('contracts/generated/openapi.json')
CLIENT = Path('packages/api-client/src/generated.ts')
RUNTIME = Path('packages/api-client/src/runtime.ts')
PYTHON = Path('services/agent/.venv/bin/python')
HEADER = '// Generated by scripts/generate_contracts.py from contracts/generated/openapi.json. Do not edit.\n'
METHODS = ('get', 'post', 'put', 'patch', 'delete')
# The BFF sets these from the verified session (apps/web/lib/bff-policy.ts apiHeaders), so no caller
# passes them and the generated functions don't take them (R-48).
BFF_HEADERS = frozenset({'authorization', 'x-autobots-internal', 'x-autobots-workspace'})
IDENTIFIER = re.compile(r'^[A-Za-z_$][\w$]*$')


def schema_name(reference: str) -> str:
    return reference.rsplit('/', 1)[-1]


def typescript_type(schema: Mapping) -> str:
    if '$ref' in schema:
        return schema_name(schema['$ref'])
    if 'const' in schema:
        return json.dumps(schema['const'])
    if 'enum' in schema:
        return ' | '.join(json.dumps(value) for value in schema['enum'])
    if 'anyOf' in schema:
        return ' | '.join(typescript_type(option) for option in schema['anyOf'])
    kind = schema.get('type')
    if kind == 'array':
        item = typescript_type(schema.get('items', {}))
        # A union of items needs parentheses, or `[]` binds to its last member only.
        return f"({item})[]" if ' | ' in item else f"{item}[]"
    if kind == 'object' and 'properties' not in schema:
        values = schema.get('additionalProperties')
        return f'Record<string, {typescript_type(values)}>' if isinstance(values, Mapping) else 'Record<string, unknown>'
    return {'string': 'string', 'integer': 'number', 'number': 'number', 'boolean': 'boolean', 'null': 'null'}.get(kind, 'unknown')


def runtime_keywords(root: Path) -> frozenset[str]:
    """IMPLEMENTED_KEYWORDS and ANNOTATIONS from the hand-written runtime, the one place they're listed."""
    text = (root / RUNTIME).read_text()
    lists = re.findall(r'export const (?:IMPLEMENTED_KEYWORDS|ANNOTATIONS) = \[(.*?)\] as const;', text, re.S)
    formats = re.findall(r'export const IMPLEMENTED_FORMATS = \[(.*?)\] as const;', text, re.S)
    if len(lists) != 2 or len(formats) != 1:
        raise ValueError(f'{RUNTIME} must export IMPLEMENTED_KEYWORDS, ANNOTATIONS and IMPLEMENTED_FORMATS')
    keywords = frozenset(re.findall(r'"([^"]+)"', ''.join(lists)))
    # A format value counts as `format:<value>`, so an unenforced format is refused like a keyword.
    return keywords | {f'format:{value}' for value in re.findall(r'"([^"]+)"', formats[0])}


def unknown_keywords(document: Mapping, known: frozenset[str]) -> list[str]:
    """Schema keywords the runtime neither enforces nor may ignore (R-03)."""
    found: set[str] = set()

    def walk(node: object) -> None:
        if not isinstance(node, Mapping):
            return
        found.update(node)
        if isinstance(node.get('format'), str):
            found.add(f"format:{node['format']}")
        for key in ('items', 'additionalProperties'):
            walk(node.get(key))
        for option in node.get('anyOf', ()):
            walk(option)
        for child in node.get('properties', {}).values():
            walk(child)

    for schema in document['components']['schemas'].values():
        walk(schema)
    return sorted(found - known)


def declaration(name: str, schema: Mapping) -> str:
    if 'properties' not in schema:
        return f'export type {name} = {typescript_type(schema)};\n'
    required = set(schema.get('required', ()))
    fields = ''.join(f"  {field}{'' if field in required else '?'}: {typescript_type(value)};\n"
                     for field, value in sorted(schema['properties'].items()))
    return f'export interface {name} {{\n{fields}}}\n'


def operation_name(details: Mapping) -> str:
    return re.sub(r'\W+(\w)', lambda match: match[1].upper(), details['operationId'])


def declared(details: Mapping, place: str) -> list[Mapping]:
    """The operation's parameters in `place` (query or header), in the contract's order, without the BFF's."""
    return [parameter for parameter in details.get('parameters', ())
            if parameter['in'] == place and not (place == 'header' and parameter['name'].lower() in BFF_HEADERS)]


def parameter_types(details: Mapping) -> dict[str, tuple[str, list[Mapping]]]:
    """Each kind of parameter the operation declares, `query` or `headers`, with its type's name and
    its parameters, such as `ListRunsQuery`."""
    name = operation_name(details)
    title = name[:1].upper() + name[1:]
    kinds = {'query': (f'{title}Query', declared(details, 'query')),
             'headers': (f'{title}Headers', declared(details, 'header'))}
    return {kind: typed for kind, typed in kinds.items() if typed[1]}


def parameter_type(name: str, parameters: list[Mapping]) -> str:
    """One kind of parameter as an object type, which a value left out may also be undefined in."""
    def field(parameter: Mapping) -> str:
        key = parameter['name'] if IDENTIFIER.match(parameter['name']) else json.dumps(parameter['name'])
        kind = typescript_type(parameter.get('schema', {}))
        return f'  {key}: {kind};\n' if parameter.get('required') else f'  {key}?: {kind} | undefined;\n'
    return f"export type {name} = {{\n{''.join(field(parameter) for parameter in parameters)}}};\n\n"


def signature(arguments: list[tuple[str, str, bool]]) -> str:
    """The arguments after `options`. An optional one takes `?` only when nothing required follows it."""
    written = []
    for index, (name, kind, required) in enumerate(arguments):
        if required:
            written.append(f', {name}: {kind}')
        elif any(later for _, _, later in arguments[index + 1:]):
            written.append(f', {name}: {kind} | undefined')
        else:
            written.append(f', {name}?: {kind}')
    return ''.join(written)


def operation(path: str, method: str, details: Mapping, error_parser: str = 'parseErrorResponse') -> str:
    """One client function, from a route with an operationId and a JSON response model."""
    responses = details['responses']
    success = next((responses[code] for code in ('200', '201', '202') if code in responses), {})
    content = success.get('content', {})
    reference = content.get('application/json', {}).get('schema', {}).get('$ref')
    if reference is None or 'operationId' not in details:
        raise ValueError(f'{method} {path} needs an operationId and a JSON response model')
    name = operation_name(details)
    response = schema_name(reference)
    arguments = [(parameter, 'string', True) for parameter in re.findall(r'{(\w+)}', path)]
    url = re.sub(r'{(\w+)}', r'${encodeURIComponent(\1)}', path)
    types = parameter_types(details)
    # R-48: a read's query is written in the contract's order, and declared headers such as
    # Idempotency-Key are arguments a caller can't leave out.
    if 'query' in types:
        kind, parameters = types['query']
        arguments.append(('query', kind, any(parameter.get('required') for parameter in parameters)))
        names = ', '.join(json.dumps(parameter['name']) for parameter in parameters)
        url += f'${{queryString(query, [{names}])}}'
    body_schema = details.get('requestBody', {}).get('content', {}).get('application/json', {}).get('schema', {}).get('$ref')
    if body_schema is not None:
        arguments.append(('body', schema_name(body_schema), True))
    if 'headers' in types:
        kind, parameters = types['headers']
        arguments.append(('headers', kind, any(parameter.get('required') for parameter in parameters)))
    payload = 'body' if body_schema is not None else 'undefined'
    request = 'withHeaders(request, headers)' if 'headers' in types else 'request'
    # R-02: a refusal carries the parsed envelope, and a call can add headers and an abort signal.
    return (''.join(parameter_type(kind, parameters) for kind, parameters in types.values())
            + f'export async function {name}(options: ClientOptions{signature(arguments)}, request?: RequestOptions): '
            f'Promise<{response}> {{\n'
            f"  return parse{response}(await requestJson(options, {json.dumps(method.upper())}, `{url}`, {payload}, {request}, "
            f'{error_parser}));\n}}\n')


def claim(emitted: set[str], names: Iterable[str], where: str) -> None:
    """Records names the client emits, refusing one it already emits, so two operationIds that
    normalize alike, or a parameter type that takes a schema's name, fail generation, not tsc (R-48)."""
    for name in names:
        if name in emitted:
            raise ValueError(f'{where}: {name} is already emitted for another schema or operation')
        emitted.add(name)


def typescript_client(document: Mapping) -> str:
    schemas = document['components']['schemas']
    parts = [HEADER, 'import { type ClientOptions, type RequestOptions, parseWith, queryString, requestJson, withHeaders } '
             "from './runtime.ts';\n\n",
             'export const schemas = ', json.dumps(schemas, indent=2, sort_keys=True), ' as const;\n\n']
    for name in sorted(schemas):
        parts.append(declaration(name, schemas[name]))
        parts.append(f'\nexport function parse{name}(value: unknown): {name} {{\n'
                     f"  return parseWith(schemas, {json.dumps(name)}, value) as {name};\n}}\n\n")
    # A refusal's body is parsed only when the contract defines the envelope.
    error_parser = 'parseErrorResponse' if 'ErrorResponse' in schemas else 'undefined'
    # Types and functions are TypeScript's two declaration spaces, so each has one set of names.
    types = set(schemas)
    functions = {f'parse{name}' for name in schemas}
    for path, entries in sorted(document.get('paths', {}).items()):
        for method in METHODS:
            if method in entries:
                text = operation(path, method, entries[method], error_parser)
                claim(types, (kind for kind, _ in parameter_types(entries[method]).values()), f'{method} {path}')
                claim(functions, (operation_name(entries[method]),), f'{method} {path}')
                parts.append(text + '\n')
    return ''.join(parts).rstrip() + '\n'


def export_document(root: Path) -> dict:
    env = {**reduced_env(), 'PYTHONPATH': str(root / 'services/agent/src'), 'PYTHONDONTWRITEBYTECODE': '1'}
    result = subprocess.run([str(root / PYTHON), '-m', 'autobots.api.openapi_export'], env=env, cwd=root,
                            capture_output=True, text=True, timeout=120, check=False)
    if result.returncode:
        raise ValueError(f'the contract export failed: {result.stderr[-400:]}')
    return json.loads(result.stdout)


def main() -> int:
    if len(sys.argv) != 2 or sys.argv[1] not in {'write', 'check'}:
        print('usage: generate_contracts.py write|check', file=sys.stderr)
        return 2
    root = project_root()
    if not (root / PYTHON).exists():
        print('ERROR: the prepared Python environment is missing; run scripts/toolchain.py bootstrap explicitly.', file=sys.stderr)
        return 2
    document = export_document(root)
    unknown = unknown_keywords(document, runtime_keywords(root))
    if unknown:
        print(f'ERROR: the runtime does not implement these schema keywords: {", ".join(unknown)}.', file=sys.stderr)
        return 1
    wanted = {OPENAPI: json.dumps(document, indent=2, sort_keys=True) + '\n', CLIENT: typescript_client(document)}
    if sys.argv[1] == 'write':
        for path, content in wanted.items():
            (root / path).parent.mkdir(parents=True, exist_ok=True)
            (root / path).write_text(content)
        return 0
    drift = [path for path, content in wanted.items()
             if not (root / path).is_file() or (root / path).read_text() != content]
    for path in drift:
        print(f'DRIFT: {path} differs from the Pydantic contracts. Review, then run scripts/generate_contracts.py write.')
    if not drift:
        print('PASS: generated contracts match the Pydantic models.')
    return 1 if drift else 0


if __name__ == '__main__':
    raise SystemExit(main())
