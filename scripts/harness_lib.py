def in_non_input_tree(relative: Path) -> bool:
    return any(relative.is_relative_to(tree) for tree in NON_INPUT_TREES)


def input_files(root: Path, base: Path) -> Iterator[Path]:
    """Files under `base`, without descending into environments, caches, build output or other checkouts."""
    for directory, children, files in os.walk(base):
        children[:] = [name for name in children if name not in NON_INPUT_DIRECTORIES
                       and not in_non_input_tree(Path(directory, name).relative_to(root))]
        # os.walk lists a link to a directory among the directories, and never enters it.
        links = [name for name in children if os.path.islink(Path(directory) / name)]
        yield from (Path(directory) / name for name in (*files, *links))


def input_manifest(root: Path) -> dict[str, str]:
    """Hash relevant nonsecret inputs, including untracked files, not report outputs."""
    root = root.resolve()
    paths = set(root.glob('PRD*.md'))
    paths.update(root / name for name in ('AGENTS.md', 'CLAUDE.md', 'CODEBASE.md',
                                         'SPECS.md', 'README.md', '.gitignore', *APP_INPUT_FILES,
                                         *GATE_CONFIG_DOMAINS))
    try:
        mapping = json.loads((root / '.claude/autobots.json').read_text()).get('documents', {})
        for value in mapping.values():
            if isinstance(value, str):
                mapped = (root / value).resolve()
                if mapped.is_relative_to(root.resolve()) and mapped.suffix == '.md':
                    paths.add(mapped)
    except (OSError, ValueError, AttributeError):
        pass  # Configuration validation reports malformed maps; never read outside root.
    for directory in ('.claude', 'scripts', 'tests/harness', 'docs/engineering', 'docs/design', 'tests/qualification', *APP_INPUT_DIRECTORIES):
        paths.update(input_files(root, root / directory))
    manifest = {}
    for path in sorted(paths):
        relative = path.relative_to(root)
        if not is_non_input(relative, path):
            # A link is an input too, by its target's name and never by what it points at.
            if path.is_symlink():
                manifest[relative.as_posix()] = 'symlink:' + hashlib.sha256(os.readlink(path).encode()).hexdigest()
            elif path.is_file():
                manifest[relative.as_posix()] = hashlib.sha256(path.read_bytes()).hexdigest()
    return manifest


def is_secret_name(name: str) -> bool:
    """Whether a file of this name holds a secret. Case-folded, because this machine's default filesystem is
    case-insensitive."""
    folded = name.casefold()
    return folded in SECRET_FILE_NAMES or ((folded == '.env' or folded.startswith('.env.')) and not folded.endswith('.example'))


def is_non_input(relative: Path, path: Path) -> bool:
    text = relative.as_posix()
    # Evidence is excluded so a report does not fingerprint itself. The fixture is read by tests.
    evidence = text.startswith('docs/engineering/evidence/') and 'forward-fixture' not in relative.parts
    # No secret is hashed into a report (PRD-Development-Harness DH-09.2), by any name the hook refuses (SCRP-13).
    secret = (path.name.startswith('.env') and not path.name.endswith('.example')) or is_secret_name(path.name)
    return (evidence or secret
            or bool(NON_INPUT_DIRECTORIES.intersection(relative.parts))
            or path.name in {'next-env.d.ts', 'approvals.local.json', 'settings.local.json'}
            or in_non_input_tree(relative)
            or path.suffix in {'.pyc', '.log', '.tsbuildinfo'})


def manifest_fingerprint(manifest: Mapping[str, str]) -> str:
    encoded = json.dumps(manifest, sort_keys=True, separators=(',', ':'))
    return hashlib.sha256(encoded.encode()).hexdigest()


def fingerprint(root: Path) -> str:
    return manifest_fingerprint(input_manifest(root))


def imported_modules(node: ast.AST) -> list[str]:
    """The dotted module names an import statement may load: `from a.b import c` may load a.b or a.b.c."""
    if isinstance(node, ast.Import):
        return [alias.name for alias in node.names]
    if isinstance(node, ast.ImportFrom) and node.module and not node.level:
        return [node.module, *(f'{node.module}.{alias.name}' for alias in node.names)]
    return []


def module_files(root: Path, name: str) -> list[Path]:
    """Where a module of scripts/ would live, as a file or a package, with each enclosing package."""
    parts = name.split('.')
    packages = [root / 'scripts' / Path(*parts[:depth]) / '__init__.py' for depth in range(1, len(parts) + 1)]
    return [root / 'scripts' / Path(*parts[:-1], f'{parts[-1]}.py'), *packages]


def import_closure(root: Path, entries: Iterable[str]) -> frozenset[str]:
    """These scripts and every scripts/ file they import, transitively, as repository-relative paths. Read with
    ast, so an import inside a function counts too. A file that doesn't parse is kept, without its imports."""
    pending = [root / entry for entry in entries]
    found: set[Path] = set()
    while pending:
        path = pending.pop()
        if path in found or not path.is_file():
            continue
        found.add(path)
        try:
            tree = ast.parse(path.read_text())
        except (OSError, SyntaxError, UnicodeError, ValueError):
            continue
        for node in ast.walk(tree):
            pending.extend(file for name in imported_modules(node) for file in module_files(root, name))
    return frozenset(path.relative_to(root).as_posix() for path in found)


def derived_domains(root: Path) -> dict[str, frozenset[str]]:
    """The domains each scripts/ file under `root` has because a profile's scripts import it (SCRP-06)."""
    derived: dict[str, frozenset[str]] = {}
    for entries, domains in closure_domains():
        for path in import_closure(root, entries):
            derived[path] = derived.get(path, frozenset()) | domains
    return derived


def check_domains(relative: str, root: Path | None = None, *, derived: Mapping[str, frozenset[str]] | None = None) -> set[str]:
    """The check domains a repository-relative path affects. Given the checkout's root, or its `derived_domains`,
    a script also has the domains of every profile whose scripts import it. That only adds a domain."""
    if relative in GATE_CONFIG_DOMAINS:
        return set(GATE_CONFIG_DOMAINS[relative])
    domains = _base_domains(relative)
    closure = derived if derived is not None else derived_domains(root) if root is not None else {}
    added = closure.get(relative, frozenset())
    if added:
        # `harness` means that no other domain applies, which is no longer so.
        domains = (domains | added) - {'harness'}
    if (relative.endswith('.py') and relative.startswith(REPO_PYTHON_PREFIXES)
            and not relative.startswith('tests/faults/')):
        domains.add('repo_python')
    return domains


def _base_domains(relative: str) -> set[str]:
    if relative.startswith('services/agent/'):
        return {'python'}
    if relative.startswith(DB_CHECK_PREFIXES) or relative in DB_CHECK_FILES:
        return {'db'}
    if relative.startswith(('apps/web/', 'packages/')):
        return {'web'}
    if relative in RUNNER_FILES or relative.startswith(RUNNER_PREFIXES):
        return {'python', 'web', 'db'}
    if relative in SHARED_CHECK_FILES or relative.startswith(SHARED_CHECK_PREFIXES):
        return {'python', 'web'}
    return {'harness'}


def read_json(path: Path) -> object:
    """The JSON a file holds, or None when it can't be read or parsed."""
    try:
        data: object = json.loads(path.read_text())
    except (OSError, ValueError):
        return None
    return data


def read_report(root: Path, profile: str) -> dict[str, Any] | None:
    data = read_json(root / '.checks' / profile / 'latest.json')
    return data if isinstance(data, dict) else None


def passing_manifest(root: Path, profiles: Iterable[str]) -> dict[str, str] | None:
    """The input manifest of the newest passing report among these profiles, or None."""
    reports = [report for profile in profiles if (report := read_report(root, profile)) is not None
               and report.get('profile') == profile and report.get('status') == 'passed'
               and report.get('template') is False and report.get('inputs_unchanged_during_check') is True
               and isinstance(report.get('input_manifest'), dict)]
    return max(reports, key=lambda report: str(report.get('completed_at_utc', '')))['input_manifest'] if reports else None


def scope_paths(root: Path, profiles: Iterable[str] = APPLICATION_PROFILES,
                manifest: Mapping[str, str] | None = None) -> list[str] | None:
    """Inputs that differ from the last passing report, or None when none exists. A clean Git tree proves nothing.
    `manifest` is the current input manifest, when the caller has already computed it."""
    base = passing_manifest(root, profiles)
    if base is None:
        return None
    current = input_manifest(root) if manifest is None else manifest
    return sorted(path for path in current.keys() | base.keys() if current.get(path) != base.get(path))


def needs_profile(root: Path, profiles: Iterable[str], domains: set[str], *, manifest: Mapping[str, str] | None = None,
                  derived: Mapping[str, frozenset[str]] | None = None) -> bool:
    """Whether these domains hold inputs no passing report of these profiles has seen."""
    current = input_manifest(root) if manifest is None else manifest
    closure = derived_domains(root) if derived is None else derived
    changed = scope_paths(root, profiles, current)
    paths = current if changed is None else changed
    return any(check_domains(path, derived=closure) & domains for path in paths)


def report_state(root: Path, profile: str = 'harness', manifest: Mapping[str, str] | None = None) -> tuple[bool, str]:
    """Whether the last `profile` report passed, holds every check its profile requires, and saw today's inputs.
    `manifest` is the current input manifest, when the caller has already computed it (SCRP-12)."""
    data = read_json(root / '.checks' / profile / 'latest.json')
    if data is None:
        return False, f'No readable {profile} report exists.'
    if not isinstance(data, dict):
        return False, f'The {profile} report is not a valid result object.'
    if (data.get('schema_version') != 'autobots.harness-result/v1'
            or data.get('template') is not False
            or data.get('inputs_unchanged_during_check') is not True):
        return False, 'The report is a template, incomplete, or records changing inputs.'
    if data.get('status') != 'passed' or data.get('profile') != profile:
        return False, f'The last {profile} check did not pass.'
    checks = data.get('checks')
    if not isinstance(checks, list) or not all(isinstance(check, dict) for check in checks):
        return False, 'The report lacks the required successful checks.'
    from qualification.profiles import PROFILES, UNCOMMANDED_CHECKS, required_checks

    if profile not in PROFILES:
        return False, f'{profile} is not a verification profile.'
    ids = {check.get('id') for check in checks}
    # Only a profile that selects by change, `fast`, may leave steps out, and each one stays visible as `not_run`.
    allowed = {'passed', 'not_run'} if PROFILES[profile].selects_by_change else {'passed'}
    required = required_checks(profile)
    complete = ids == required if profile == 'harness' else required <= ids
    if not complete:
        return False, 'The report lacks the required successful checks.'
    if (any(check.get('status') not in allowed for check in checks)
            or any(check.get('status') != 'passed' for check in checks if check.get('id') in required)):
        return False, 'The report lacks the required successful checks.'
    for check in checks:
        if (check.get('status') != 'not_run' and check.get('id') not in UNCOMMANDED_CHECKS
                and check.get('exit_code') != 0):
            return False, 'The report does not record successful command execution.'
        if check.get('id') == 'harness_behavior_tests' and (
                type(check.get('tests_executed')) is not int or check['tests_executed'] < 1):
            return False, 'An empty or missing behavioral suite cannot pass.'
        if check.get('tests_skipped'):
            return False, 'A skipped test is not a passing test.'
    current = input_manifest(root) if manifest is None else manifest
    if data.get('input_fingerprint') != manifest_fingerprint(current) or data.get('input_manifest') != current:
        return False, f'Source/configuration inputs changed after the last {profile} check.'
    return True, f'Current {profile} checks passed; other profiles and live gates remain separate.'


def evidence_state(root: Path) -> tuple[bool, str]:
    """Whether current reports cover what changed since each profile last passed. The input manifest and the import
    closures are computed once for the whole evaluation, inside the hook's deadline (SCRP-12)."""
    manifest = input_manifest(root)
    derived = derived_domains(root)
    groups: list[tuple[str, ...]] = []
    if needs_profile(root, APPLICATION_PROFILES, {'python', 'web', 'repo_python'}, manifest=manifest, derived=derived):
        groups.append(APPLICATION_PROFILES)
    if needs_profile(root, ('db',), {'db'}, manifest=manifest, derived=derived):
        groups.append(('db',))
    for group in groups or [('harness', *APPLICATION_PROFILES, 'db', 'operations')]:
        states = [report_state(root, profile, manifest) for profile in group]
        if not any(state[0] for state in states):
            return False, f"Inputs changed since the last passing {' or '.join(group)} report, and none is current."
    return True, 'Current reports cover the changed scope; live gates remain separate.'


def config_errors(root: Path) -> list[str]:
    """Every way the project configuration differs from the reviewed baseline, as `project_configuration` reports it:
    the document mappings, the hooks, the instruction files' frontmatter and links, the rules' check links and the
    AGENTS.md mapping (PRD-Development-Harness DH-05, refactor plan R-66 THRN-05)."""
    # Imported here, so a script that uses only this module's other helpers runs from a copy without it.
    from instruction_checks import broken_link_errors, frontmatter_errors, parse_frontmatter

    errors = []
    try:
        config = json.loads((root / '.claude/autobots.json').read_text())
        settings = json.loads((root / '.claude/settings.json').read_text())
    except (OSError, ValueError) as exc:
        return [f'Configuration unreadable: {type(exc).__name__}']
    if not isinstance(config, dict) or not isinstance(settings, dict):
        return ['Configuration must contain JSON objects.']
    errors.extend(activation_errors(config))
    interpreter = config.get('python_executable')
    if (not isinstance(interpreter, str) or not Path(interpreter).is_absolute()
            or not Path(interpreter).is_file() or not os.access(interpreter, os.X_OK)):
        errors.append('Configure an existing absolute path to the qualified Python 3.12+ interpreter.')
    documents = config.get('documents')
    if not isinstance(documents, dict):
        return ['Document mappings must be an object.']
    for key in ('specs', 'codebase', 'contract', 'product', 'harness', 'providers',
                'deployment', 'research', 'comparison'):
        value = documents.get(key)
        if not isinstance(value, str):
            errors.append(f'Missing document mapping: {key}')
            continue
        dest = (root / value).resolve()
        if not dest.is_relative_to(root.resolve()) or not dest.is_file() or dest.suffix != '.md':
            errors.append(f'Invalid local document mapping: {key}')
    if set(settings) != {'hooks'}:
        errors.append('Baseline settings permit only the reviewed hooks; disabling hooks or changing model/env/permissions is unsupported.')
    hooks = settings.get('hooks', {})
    if not isinstance(hooks, dict):
        return [*errors, 'Hook configuration must be an object.']
    expected = {'SessionStart', 'PreToolUse', 'PostToolUse', 'Stop', 'SubagentStop'}
    if set(hooks) != expected:
        errors.append('Unexpected or missing baseline hook events.')
    for event, groups in hooks.items():
        if not isinstance(groups, list) or len(groups) != 1:
            errors.append(f'{event}: expected one nonempty hook group.')
            continue
        for group in groups:
            if not isinstance(group, dict):
                errors.append(f'{event}: invalid hook group.')
                continue
            if set(group) - {'matcher', 'hooks'}:
                errors.append(f'{event}: unexpected hook group options.')
            matchers = {'PreToolUse': 'Read|Write|Edit|MultiEdit|Bash',
                        'PostToolUse': 'Write|Edit|MultiEdit'}
            if event in matchers and group.get('matcher') != matchers[event]:
                errors.append(f'{event}: expected the reviewed tool matcher.')
            if event not in matchers and 'matcher' in group:
                errors.append(f'{event}: no matcher is used in this baseline.')
            handlers = group.get('hooks')
            if not isinstance(handlers, list) or len(handlers) != 1:
                errors.append(f'{event}: expected one nonempty command handler.')
                continue
            for hook in handlers:
                if not isinstance(hook, dict):
                    errors.append(f'{event}: invalid hook handler.')
                    continue
                expected_keys = {'type', 'command', 'args', 'timeout'}
                if event == 'PreToolUse':
                    expected_keys.add('onFailure')
                if set(hook) != expected_keys:
                    errors.append(f'{event}: unexpected or missing handler options; asynchronous enforcement is unsupported.')
                if hook.get('type') != 'command' or hook.get('command') != interpreter:
                    errors.append(f'{event}: only the local Python dispatcher is supported.')
                if hook.get('args') != ['${CLAUDE_PROJECT_DIR}/.claude/hooks/dispatch.py']:
                    errors.append(f'{event}: unexpected dispatcher arguments.')
                if not isinstance(hook.get('timeout'), int) or not 1 <= hook['timeout'] <= 10:
                    errors.append(f'{event}: hook needs a bounded timeout.')
                if event == 'PreToolUse' and hook.get('onFailure') != 'block':
                    errors.append('PreToolUse must block on startup failure/timeout.')
    for directory in ('skills', 'agents', 'rules'):
        found = list((root / '.claude' / directory).rglob('*.md'))
        if not found:
            errors.append(f'No project {directory} exist.')
        for path in found:
            text = path.read_text()
            if directory in {'skills', 'agents'}:
                keys = parse_frontmatter(text)
                if keys is None:
                    errors.append(f'{path.relative_to(root)}: missing frontmatter.')
                    continue
                if 'name' not in keys:
                    errors.append(f'{path.relative_to(root)}: missing name.')
                if 'description' not in keys:
                    errors.append(f'{path.relative_to(root)}: missing description.')
            if '${CLAUDE_PLUGIN_ROOT}' in text or 'ohmyorch:contract' in text:
                errors.append(f'{path.relative_to(root)}: unresolved upstream plugin dependency.')
    errors.extend(frontmatter_errors(root))
    errors.extend(broken_link_errors(root))
    errors.extend(rule_link_errors(root))
    errors.extend(agents_mapping_errors(root))
    return errors


def activation_errors(config: dict[str, Any]) -> list[str]:
    """Refuse an activation claim. Allowlisted exactly, because a prefix would accept `not_tested_but_active`.

    Recording real qualification later needs evidence and a deliberate change here.
    """
    errors = []
    assistant = config.get('assistant')
    assistant = assistant if isinstance(assistant, dict) else {}
    upstream = config.get('upstream')
    plugin = upstream.get('delivery_plugin') if isinstance(upstream, dict) else None
    plugin = plugin if isinstance(plugin, dict) else {}
    if assistant.get('event_delivery_qualification') != ASSISTANT_QUALIFICATION:
        errors.append(f'assistant.event_delivery_qualification must stay {ASSISTANT_QUALIFICATION!r} without recorded qualification evidence.')
    if plugin.get('event_delivery_qualification') != DELIVERY_PLUGIN_QUALIFICATION:
        errors.append(f'upstream.delivery_plugin.event_delivery_qualification must stay {DELIVERY_PLUGIN_QUALIFICATION!r} without recorded qualification evidence.')
    if assistant.get('model_configuration') != 'unchanged':
        errors.append("assistant.model_configuration must stay 'unchanged'; harness setup does not change developer-client models.")
    if parse_version(assistant.get('minimum_version_for_blocking_hook_failure')) is None:
        errors.append('assistant.minimum_version_for_blocking_hook_failure must be a three-part numeric version.')
    return errors


def unfenced_lines(text: str) -> list[str]:
    """Lines outside fenced code blocks."""
    kept = []
    opening = None
    for line in text.splitlines():
        match = FENCE.match(line)
        if opening is not None:
            if match and match[1][0] == opening[0] and len(match[1]) >= len(opening) and not match[2].strip():
                opening = None
        elif match:
            opening = match[1]
        else:
            kept.append(line)
    return kept


def line_links(line: str) -> list[str]:
    """Markdown link targets on one line, ignoring inline code spans. Link text in code still counts."""
    return [match[2] for match in LINK.finditer(INLINE_CODE.sub('', line))]


def is_allowed_target(target: str, base: Path, root: Path) -> bool:
    """Whether a link resolves to an existing check or review target from `base`."""
    parsed = urlsplit(target.removeprefix('<').removesuffix('>'))
    raw = unquote(parsed.path)
    if parsed.scheme or parsed.netloc or parsed.query or not raw or raw.startswith('/'):
        return False
    resolved = (base / raw).resolve()
    if not resolved.is_relative_to(root.resolve()) or not resolved.is_file():
        return False
    relative = resolved.relative_to(root.resolve()).as_posix()
    if relative == ALLOWED_LINK_ANCHOR[0]:
        return unquote(parsed.fragment) == ALLOWED_LINK_ANCHOR[1]
    return relative in ALLOWED_LINK_PATHS


def rule_link_errors(root: Path) -> list[str]:
    errors = []
    for path in sorted((root / '.claude/rules').rglob('*.md')):
        try:
            lines = unfenced_lines(path.read_text())
        except (OSError, ValueError):
            errors.append(f'{path.relative_to(root)}: unreadable rule file.')
            continue
        if not any(is_allowed_target(target, path.parent, root)
                   for line in lines for target in line_links(line)):
            errors.append(f'{path.relative_to(root)}: no Markdown link to an allowed check or review target.')
    return errors


def agents_mapping_errors(root: Path) -> list[str]:
    """Each rule-bearing AGENTS.md section needs a row linking to a check or review target."""
    try:
        lines = unfenced_lines((root / 'AGENTS.md').read_text())
    except (OSError, ValueError):
        return ['AGENTS.md: unreadable, so its rules cannot be mapped to checks and review.']
    headings = [line[3:].strip() for line in lines if line.startswith('## ')]
    if AGENTS_MAPPING_HEADING not in headings:
        return [f'AGENTS.md: missing the "## {AGENTS_MAPPING_HEADING}" section.']
    section = []
    inside = False
    for line in lines:
        if line.startswith('## '):
            inside = line[3:].strip() == AGENTS_MAPPING_HEADING
        elif inside:
            section.append(line)
    table = [line.strip() for line in section if line.strip().startswith('|')]
    errors = []
    rows = {}
    for line in table[2:]:  # The first two lines are the table's header and separator.
        cells = line.strip('|').split('|')
        label = LINK.sub(lambda match: match[1], cells[0]).replace('`', '').strip()
        rows[label] = line
        if not any(is_allowed_target(target, root, root) for target in line_links('|'.join(cells[1:]))):
            errors.append(f'AGENTS.md: row "{label}" has no link to an allowed check or review target.')
    required = [heading for heading in headings if heading != AGENTS_MAPPING_HEADING]
    for label in [*required, *AGENTS_REQUIRED_ROWS]:
        if label not in rows:
            errors.append(f'AGENTS.md: no mapping row for "{label}".')
    return errors


def parse_version(value: object) -> tuple[int, ...] | None:
    """A three-part numeric version, or None. Numeric, because 2.1.99 < 2.1.295 < 2.1.1000."""
    if not isinstance(value, str) or re.fullmatch(VERSION, value) is None:
        return None
    return tuple(int(part) for part in value.split('.'))


@dataclass(frozen=True)
class Bounded:
    """What a bounded process did. `exit_code` is None when it could not start, its `failure` the error's type name,
    or when it outlived its deadline, `failure` 'timeout'."""

    exit_code: int | None
    stdout: str
    stderr: str
    failure: str | None = None


def run_bounded(argv: Sequence[str], *, cwd: Path, env: Mapping[str, str], timeout: float,
                stderr: int = subprocess.PIPE) -> Bounded:
    """Run a process in its own session with no stdin, so a timeout kills its whole process group: a child holding
    the captured pipes open would otherwise outlive the deadline (XTOL-16, SCRP-18). `stderr` is a subprocess
    constant: PIPE keeps it apart, STDOUT merges it and DEVNULL drops it."""
    try:
        process = subprocess.Popen(list(argv), cwd=cwd, env=dict(env), stdin=subprocess.DEVNULL, stdout=subprocess.PIPE,
                                   stderr=stderr, text=True, errors='replace', start_new_session=True)
    except OSError as error:
        return Bounded(None, '', '', type(error).__name__)
    try:
        output, errors = process.communicate(timeout=timeout)
    except subprocess.TimeoutExpired:
        try:
            os.killpg(process.pid, signal.SIGKILL)
        except (ProcessLookupError, PermissionError):
            process.kill()
        try:
            process.communicate(timeout=1)
        except subprocess.TimeoutExpired:
            pass  # A descendant left its group and holds the pipe; the run has failed regardless.
        return Bounded(None, '', '', 'timeout')
    return Bounded(process.returncode, output or '', errors or '')


def utc() -> str:
    return datetime.now(UTC).isoformat()


def parse_dotenv(text: str, mode: DotenvMode) -> dict[str, str]:
    """`NAME=value` lines as a mapping, for the scripts' one reading of an env file (SCRP-16). A line it can't read
    is skipped: nothing is raised, printed or logged, so no value can reach a console or a report.

    `app` reads as the service does (autobots.application.credentials.precedence.parse_dotenv): comments,
    `export`, matching single or double quotes and a trailing ` #` comment. tests/harness/test_dotenv.py holds
    the two to the same fixtures. `verbatim` keeps every value as written, quotes included, as the install has
    always read stack.env and the file its values come from, upstream's env.example.

    Open question for the owner: whether stack.env should be read as the app reads. That strips the quotes
    env.example puts on its four MAILER_URLPATHS_* values, so GoTrue would get them unquoted and the install's
    auth container would be recreated at its next start, a change to the persistent install that this reading
    must not make by itself (SCRP-16).
    """
    values = {}
    for raw in text.splitlines():
        line = raw.strip()
        if not line or line.startswith('#') or '=' not in line:
            continue
        name, _, value = line.partition('=')
        value = value.strip()
        if mode == 'verbatim':
            values[name.strip()] = value
            continue
        if len(value) >= 2 and value[0] in '"\'' and value[-1] == value[0]:
            value = value[1:-1]
        elif ' #' in value:
            value = value.split(' #', 1)[0].rstrip()
        values[name.strip().removeprefix('export ').strip()] = value
    return values


def probe_version(executable: str, root: Path, timeout: float) -> str | None:
    """Run only `<executable> --version`. Failure, timeout and unparsable output all give None. The path is
    never recorded."""
    result = run_bounded([executable, '--version'], cwd=root, env=reduced_env(), timeout=timeout, stderr=subprocess.DEVNULL)
    if result.exit_code != 0:
        return None
    match = re.match(rf'\s*({VERSION})(?:\s|$)', result.stdout)
    return match[1] if match else None


def configured_minimum(root: Path) -> str | None:
    try:
        config = json.loads((root / '.claude/autobots.json').read_text())
        minimum = config['assistant']['minimum_version_for_blocking_hook_failure']
    except (OSError, ValueError, KeyError, TypeError):
        return None
    return minimum if parse_version(minimum) is not None else None


def adapter_status(root: Path, *, lookup: Callable[[str], str | None] = shutil.which,
                   timeout: float = VERSION_TIMEOUT_SECONDS) -> dict[str, Any]:
    """Derive the optional Claude adapter's state; the first matching condition wins.

    Covers one observation: the CLI's presence and version, and the validity of this
    repository's project configuration. It does not separate project hooks from plugin hooks,
    does not establish effective settings across scopes, and does not check the developer
    client's model route, so `configured_unqualified` must not be read as compatible.
    The status never fails verification, because an unavailable adapter must not block the
    portable runner. State values are never `active` or `qualified`.
    """
    minimum = configured_minimum(root)
    status = {'state': 'inactive', 'reason': '', 'minimum_version': minimum, 'model_route': 'not_checked'}
    executable = lookup('claude')
    if executable is None:
        return status | {'reason': 'unavailable'}
    if minimum is None:
        return status | {'reason': 'minimum_unknown'}
    if config_errors(root):
        return status | {'reason': 'configuration_invalid'}
    observed = probe_version(executable, root, timeout)
    if observed is None:
        return status | {'reason': 'version_unknown'}
    status['observed_version'] = observed
    observed_parts, minimum_parts = parse_version(observed), parse_version(minimum)
    if observed_parts is None or minimum_parts is None:
        return status | {'reason': 'version_unknown'}
    if observed_parts < minimum_parts:
        return status | {'reason': 'version_below_minimum'}
    return status | {'state': 'configured_unqualified', 'reason': 'delivery_unverified'}
