#!/usr/bin/env python3
"""Guarded application migrations and seeds, on a marked disposable target. No persistent path exists here.

`qualify` creates a new disposable database on the pinned image and proves replay, upgrade, seed
repeatability, constraints, row-level access and migration authority. `types` regenerates public row
types from the same migrations, and `qualify` fails if they drift. Only the migration identity runs
DDL, and nothing here touches a persistent target or starts a worker.

Exit codes: 0 passed, 1 a case failed or the target was refused, 2 prerequisite unavailable.
Passing establishes neither H1 nor product acceptance.
"""
from __future__ import annotations

from collections.abc import Sequence
from datetime import datetime, timezone
import hashlib
import json
from pathlib import Path
import re
import secrets
import subprocess
import sys
import time

from disposable_db import (PROJECT_PREFIX, Cases, Refused, Target, Unavailable, free_port, last_line, other_resources,
                           remove_stack, require_identity, require_marker, rows, run, tool_env, write_marker)
from harness_lib import fingerprint, project_root
from supabase_stack import SupabaseStack, generated_values, require_images, require_rendered

MIGRATIONS = Path('supabase/migrations')
ROLES = Path('supabase/bootstrap/roles.sql')
SEEDS = Path('supabase/seeds/reference.sql')
BAD_MIGRATIONS = Path('tests/db/app_bad_migrations')
FIXTURE = Path('tests/db/app_fixture.sql')
ROW_TYPES = Path('packages/db-types/src/generated.ts')
REPORT = Path('.checks/app_db/qualification.json')
MIGRATION_NAME = re.compile(r'\d{14}_[a-z0-9_]+\.sql')
USER_A, USER_B = 'a1111111-1111-4111-8111-111111111111', 'b2222222-2222-4222-8222-222222222222'
RUN_A = 'a3333333-3333-4333-8333-333333333333'
WORKSPACE_A = 'a0000000-0000-4000-8000-000000000001'
TS_TYPES = {'uuid': 'string', 'text': 'string', 'timestamp with time zone': 'string', 'bigint': 'number',
            'integer': 'number', 'boolean': 'boolean', 'jsonb': 'unknown'}
HEADER = '// Generated by scripts/app_db.py types from the public schema. Do not edit.\n'
# Code outside the guarded path must not own schema. Scanned by a harness test too.
FORBIDDEN_DDL = re.compile(r'alembic|create_all\(|metadata\.create|\.setup\(\)|\bcreate\s+table\b|\balter\s+table\b', re.IGNORECASE)


class AppStack(SupabaseStack):
    migrator_password: str = ''
    runtime_password: str = ''

    def as_login(self, role: str, password: str, statements: str) -> subprocess.CompletedProcess[str]:
        """Connect as a real login role over TCP inside the container, so its privileges are what is tested."""
        return self.compose('exec', '-T', '-e', f'PGPASSWORD={password}', 'db', 'psql', '-h', 'localhost', '-U', role,
                            '-d', 'postgres', '-X', '-q', '-A', '-t', '-v', 'ON_ERROR_STOP=1', stdin=statements)

    def migrator(self, statements: str) -> subprocess.CompletedProcess[str]:
        return self.as_login('autobots_migrator', self.migrator_password, statements)

    def runtime(self, statements: str) -> subprocess.CompletedProcess[str]:
        return self.as_login('autobots_runtime', self.runtime_password, statements)

    def as_role(self, role: str, user: str | None, statement: str) -> subprocess.CompletedProcess[str]:
        claims = json.dumps({'role': role, **({'sub': user} if user else {})})
        return self.sql(f"begin;\nset local role {role};\nselect set_config('request.jwt.claims', '{claims}', true), "
                        f"set_config('request.jwt.claim.sub', '{user or ''}', true);\n{statement};\nrollback;\n")


def bootstrap(stack: AppStack, root: Path) -> None:
    roles = stack.sql(f"\\set migrator_password '{stack.migrator_password}'\n\\set runtime_password '{stack.runtime_password}'\n"
                      f'{(root / ROLES).read_text()}')
    if roles.returncode:
        raise Unavailable(f'the role bootstrap failed: {roles.stderr[-300:]}')
    write_marker(stack)
    history = stack.sql('grant usage on schema autobots_disposable to autobots_migrator;\n'
                        'grant select, insert on autobots_disposable.migrations to autobots_migrator;\n'
                        'grant select on autobots_disposable.marker to autobots_migrator;\n')
    if history.returncode:
        raise Unavailable(f'the history grant failed: {history.stderr[-300:]}')


def apply_migrations(stack: AppStack, directory: Path, upto: int | None = None) -> tuple[int, str | None]:
    """In name order, each with its history row in one transaction, as the migration identity only."""
    require_marker(stack)
    listing = stack.migrator('select name, sha256 from autobots_disposable.migrations;')
    if listing.returncode:
        return 0, 'the migration history is unreadable'
    recorded = dict(line.split('|') for line in listing.stdout.splitlines() if line)
    applied = 0
    for path in sorted(directory.glob('*.sql'))[:upto]:
        if not MIGRATION_NAME.fullmatch(path.name):
            return applied, f'{path.name} is not named <14 digit timestamp>_<description>.sql'
        checksum = hashlib.sha256(path.read_bytes()).hexdigest()
        if path.name in recorded:
            if recorded[path.name] != checksum:
                return applied, f'{path.name} changed after it was applied; never edit an applied migration'
            continue
        result = stack.migrator(f"begin;\n{path.read_text()}\ninsert into autobots_disposable.migrations values "
                                f"('{path.name}', '{checksum}');\ncommit;\n")
        if result.returncode:
            return applied, f'{path.name} failed and was rolled back: {result.stderr.strip()[-160:]}'
        applied += 1
    return applied, None


def seed(stack: AppStack, root: Path) -> subprocess.CompletedProcess[str]:
    """Reference data only. Runs as the migration identity, explicitly, after migrations."""
    return stack.migrator(f'begin;\n{(root / SEEDS).read_text()}\ncommit;\n')


def reset(stack: AppStack) -> None:
    require_marker(stack)
    result = stack.sql('drop schema if exists app_private cascade;\ndrop schema if exists agent_runtime cascade;\n'
                       'drop table if exists public.run_events, public.runs, public.model_profiles, public.workspace_members, '
                       'public.workspaces cascade;\ndrop function if exists public.is_workspace_member(uuid);\n'
                       'truncate autobots_disposable.migrations;\n')
    if result.returncode:
        raise Unavailable(f'the disposable reset failed: {result.stderr[-200:]}')


def public_columns(stack: AppStack) -> list[tuple[str, str, str, str]]:
    result = stack.sql("select table_name, column_name, data_type, is_nullable from information_schema.columns "
                       "where table_schema = 'public' order by table_name, ordinal_position;")
    if result.returncode:
        raise Unavailable('could not read the public columns')
    return [tuple(line.split('|')) for line in result.stdout.splitlines() if line]  # type: ignore[misc]


def row_types(columns: Sequence[tuple[str, str, str, str]]) -> str:
    tables: dict[str, list[str]] = {}
    for table, column, kind, nullable in columns:
        base = TS_TYPES.get(kind)
        if base is None:
            raise ValueError(f'{table}.{column} has unmapped type {kind}')
        tables.setdefault(table, []).append(f"  {column}: {base}{' | null' if nullable == 'YES' else ''};\n")
    names = {table: ''.join(part.capitalize() for part in table.split('_')) + 'Row' for table in tables}
    return HEADER + '\n' + '\n'.join(f'export interface {names[table]} {{\n{"".join(lines)}}}\n' for table, lines in sorted(tables.items()))


def migration_cases(stack: AppStack, cases: Cases, root: Path) -> None:
    directory = root / MIGRATIONS
    total = len(list(directory.glob('*.sql')))
    applied, error = apply_migrations(stack, directory)
    cases.check('fresh replay as the migration identity', f'{total} applied', f'{applied} applied, {error}', applied == total and error is None)
    owner = rows(stack, "select string_agg(distinct tableowner, ',') from pg_tables where schemaname = 'public' and tablename <> 'migrations';")
    cases.check('the migration identity owns the schema', 'autobots_migrator', owner, owner == 'autobots_migrator')
    columns = rows(stack, "select count(*) from information_schema.columns where table_schema = 'public';")
    applied, error = apply_migrations(stack, directory)
    cases.check('repeated apply changes nothing', '0 applied, same columns', f'{applied} applied, {columns} columns',
                applied == 0 and error is None and columns == rows(stack, "select count(*) from information_schema.columns where table_schema = 'public';"))
    bad_applied, bad_error = apply_migrations(stack, root / BAD_MIGRATIONS)
    remains = rows(stack, "select (select count(*) from information_schema.tables where table_name = 'partial_migration') "
                          "+ (select count(*) from autobots_disposable.migrations where name like '2099%');")
    cases.check('a failing migration rolls back', 'error, nothing remains', f'{bad_applied} applied, {remains} remain',
                bad_applied == 0 and bool(bad_error) and remains == '0')
    first = sorted(directory.glob('*.sql'))[0].name
    stack.sql(f"update autobots_disposable.migrations set sha256 = 'edited' where name = '{first}';")
    _, error = apply_migrations(stack, directory)
    cases.check('an edited applied migration is refused', 'refused', str(error), bool(error and 'never edit' in error))
    reset(stack)
    applied, error = apply_migrations(stack, directory, upto=total - 1)
    fixture = stack.migrator((root / FIXTURE).read_text())
    prior = rows(stack, f"select limit_micro_usd from public.runs where id = '{RUN_A}';")
    applied_next, error = apply_migrations(stack, directory)
    upgraded = rows(stack, f"select limit_micro_usd || '|' || goal_summary from public.runs where id = '{RUN_A}';")
    cases.check('upgrade from the prior version keeps data', 'row kept, default added', f'prior {prior}, then {upgraded}, {applied_next} applied',
                fixture.returncode == 0 and applied_next == 1 and error is None and upgraded == '1000|')


def seed_cases(stack: AppStack, cases: Cases, root: Path) -> None:
    query = ("select md5(string_agg(to_jsonb(p)::text, ',' order by p.profile_id)) from public.model_profiles p;")
    first = seed(stack, root)
    before = rows(stack, query)
    second = seed(stack, root)
    after = rows(stack, query)
    cases.check('a second seed run changes nothing', 'same rows', f'{before} then {after}',
                first.returncode == 0 and second.returncode == 0 and before == after and len(before) == 32)
    profiles = rows(stack, "select string_agg(profile_id || '=' || wire_id, ',' order by profile_id) from public.model_profiles;")
    cases.check('reference rows are the two approved profiles', 'exactly SP-006', profiles,
                profiles == 'openrouter_astra=openai/gpt-6-astra,openrouter_deepseek_flash=deepseek/deepseek-v4.1-flash-1017')
    edited = stack.runtime("update public.model_profiles set label = 'My label' where profile_id = 'openrouter_astra';")
    seed(stack, root)
    label = rows(stack, "select label from public.model_profiles where profile_id = 'openrouter_astra';")
    cases.check('a repeated seed keeps a user edit', 'My label', label, edited.returncode == 0 and label == 'My label')


def constraint_cases(stack: AppStack, cases: Cases) -> None:
    run = "insert into public.runs (id, workspace_id, limit_micro_usd) values (gen_random_uuid(), '"
    for label, statement, marker in (
            ('an unknown workspace', f"{run}c0000000-0000-4000-8000-000000000009', 1)", 'foreign key'),
            ('a status outside SP-010', f"{run}{WORKSPACE_A}', 1); update public.runs set status = 'done' where id = '{RUN_A}'", 'check constraint'),
            ('negative money', f"{run}{WORKSPACE_A}', -1)", 'check constraint'),
            ('a duplicate event sequence', f"insert into public.run_events values ('{RUN_A}', 1, 1, '{{}}', now()), ('{RUN_A}', 1, 1, '{{}}', now())", 'duplicate key'),
            ('an unapproved profile', "insert into public.model_profiles values ('openrouter_other', 'x', 'y', 'z', 1)", 'check constraint')):
        result = stack.sql(f'begin;\n{statement};\nrollback;\n')
        cases.denied(f'the schema refuses {label}', result, marker)


def access_cases(stack: AppStack, cases: Cases) -> None:
    denied = 'permission denied'
    cases.denied('anonymous cannot read runs', stack.as_role('anon', None, 'select * from public.runs'), denied)
    cases.denied('anonymous cannot read private schema', stack.as_role('anon', None, 'select * from app_private.nothing'), denied)
    cases.denied('authenticated cannot read lease columns',
                 stack.as_role('authenticated', USER_A, 'select lease_generation from public.runs'), denied)
    cases.denied('authenticated cannot read the checkpoint schema',
                 stack.as_role('authenticated', USER_A, 'select * from agent_runtime.anything'), denied)
    cases.denied('authenticated cannot write runs',
                 stack.as_role('authenticated', USER_A, f"update public.runs set status = 'failed' where id = '{RUN_A}'"), denied)
    own = last_line(stack.as_role('authenticated', USER_A, 'select count(id) from public.runs'))
    cases.check('a member reads its workspace runs', '1', own, own == '1')
    other = last_line(stack.as_role('authenticated', USER_B, f"select count(id) from public.runs where id = '{RUN_A}'"))
    cases.check('another workspace reads no run', '0', other, other == '0')


def authority_cases(stack: AppStack, cases: Cases) -> None:
    denied = 'permission denied'
    for label, statement in (('create a table', 'create table public.worker_owned (id int)'),
                             ('alter a table', "alter table public.runs add column worker_column int"),
                             ('drop a table', 'drop table public.run_events'),
                             ('create a schema', 'create schema worker_schema'),
                             ('write the migration history', "insert into autobots_disposable.migrations values ('x', 'y')")):
        result = stack.runtime(f'{statement};\n')
        cases.check(f'the runtime role cannot {label}', 'refused', result.stderr.strip()[:120], result.returncode != 0
                    and ('permission denied' in result.stderr or 'must be owner' in result.stderr))
    wrote = stack.runtime(f"update public.runs set status = 'running' where id = '{RUN_A}';\n")
    cases.check('the runtime role can do its own work', 'exit 0', f'exit {wrote.returncode}', wrote.returncode == 0)
    cases.denied('authenticated cannot create a table', stack.as_role('authenticated', USER_A, 'create table public.x (id int)'), denied)


def framework_cases(stack: AppStack, cases: Cases, root: Path, db_port: int) -> None:
    """The framework's own tables go through the same path: only the migration identity may run its setup."""
    code = ('import sys\n'
            'from langgraph.checkpoint.postgres import PostgresSaver\n'
            'import psycopg\n'
            'url = sys.argv[1]\n'
            'with psycopg.connect(url, autocommit=True, options="-c search_path=agent_runtime") as connection:\n'
            '    PostgresSaver(connection).setup()\n')
    def attempt(role: str, password: str) -> subprocess.CompletedProcess[str]:
        url = f'postgresql://{role}@127.0.0.1:{db_port}/postgres'
        return subprocess.run([str(root / 'services/agent/.venv/bin/python'), '-c', code, url], env={**tool_env(), 'PGPASSWORD': password},
                              capture_output=True, text=True, errors='replace', timeout=120, check=False)
    runtime = attempt('autobots_runtime', stack.runtime_password)
    cases.check('the runtime role cannot run framework setup', 'refused', 'permission denied' if 'ermission denied' in runtime.stderr else runtime.stderr.strip()[-120:],
                runtime.returncode != 0 and 'ermission denied' in runtime.stderr)
    grant = stack.migrator('grant create on schema agent_runtime to autobots_migrator;\n')
    migrator = attempt('autobots_migrator', stack.migrator_password)
    tables = rows(stack, "select string_agg(tablename, ',' order by tablename) from pg_tables where schemaname = 'agent_runtime';")
    cases.check('the migration identity can run framework setup', 'checkpoint tables in agent_runtime', tables,
                grant.returncode == 0 and migrator.returncode == 0 and 'checkpoints' in tables)
    stack.migrator('grant select, insert, update, delete on all tables in schema agent_runtime to autobots_runtime;\n')
    used = stack.runtime('select count(*) from agent_runtime.checkpoints;\n')
    cases.check('the runtime role can use those tables', 'exit 0', f'exit {used.returncode}', used.returncode == 0)
    denied = stack.runtime('create table agent_runtime.worker_owned (id int);\n')
    cases.check('the runtime role still cannot change them', 'refused', denied.stderr.strip()[:100],
                denied.returncode != 0 and 'permission denied' in denied.stderr)


def static_cases(cases: Cases, root: Path) -> None:
    found = [path.relative_to(root).as_posix() for path in sorted((root / 'services/agent/src').rglob('*.py'))
             if FORBIDDEN_DDL.search(path.read_text())]
    cases.check('no ORM history or worker-startup DDL in service code', 'none', ', '.join(found) or 'none', not found)


def credential_cases(stack: AppStack, cases: Cases, root: Path, db_port: int) -> None:
    """Real encrypted rows through the runtime role, with arranged placeholder values and a temporary key."""
    workspace, other = 'a0000000-0000-4000-8000-000000000001', 'b0000000-0000-4000-8000-000000000002'
    url = f'postgresql://autobots_runtime:{stack.runtime_password}@127.0.0.1:{db_port}/postgres'
    process = subprocess.Popen([str(root / 'services/agent/.venv/bin/python'), str(root / 'tests/db/credential_store_check.py'), workspace, other],
                               env={**tool_env(), 'AUTOBOTS_DATABASE_URL': url, 'PYTHONPATH': str(root / 'services/agent/src'), 'PYTHONDONTWRITEBYTECODE': '1'},
                               stdin=subprocess.PIPE, stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True)
    assert process.stdin is not None and process.stdout is not None
    first = process.stdout.readline()
    if 'needs_grant' in first:
        stack.sql(f"insert into app_private.installation_credential_grants values ('{workspace}');\\n")
        process.stdin.write('\\n')
        process.stdin.flush()
    out, err = process.communicate(timeout=120)
    if process.returncode:
        cases.check('the credential store check ran', 'exit 0', f'exit {process.returncode}: {err.strip()[-300:]}', False)
        return
    for case in json.loads(out.strip().splitlines()[-1])['cases']:
        cases.check(case['id'], case['expected'], case['observed'], case['passed'])
    stored = rows(stack, "select count(*) from pg_tables where schemaname = 'public' and tablename like '%credential%';")
    cases.check('credentials are not in the exposed schema', '0 public tables', stored, stored == '0')
    denied = stack.as_role('authenticated', USER_A, 'select * from app_private.provider_credentials')
    cases.denied('authenticated cannot read credentials', denied, 'permission denied')
    denied = stack.as_role('anon', None, 'select * from app_private.provider_credentials')
    cases.denied('anonymous cannot read credentials', denied, 'permission denied')


def admission_cases(stack: AppStack, cases: Cases, root: Path, db_port: int) -> None:
    """Real concurrent reservations through the runtime role. Money here is fixture values."""
    url = f'postgresql://autobots_runtime:{stack.runtime_password}@127.0.0.1:{db_port}/postgres'
    result = subprocess.run([str(root / 'services/agent/.venv/bin/python'), str(root / 'tests/db/admission_check.py'), WORKSPACE_A],
                            env={**tool_env(), 'AUTOBOTS_DATABASE_URL': url, 'PYTHONPATH': str(root / 'services/agent/src'), 'PYTHONDONTWRITEBYTECODE': '1'},
                            capture_output=True, text=True, timeout=120, check=False)
    if result.returncode:
        cases.check('the admission check ran', 'exit 0', f'exit {result.returncode}: {result.stderr.strip()[-400:]}', False)
        return
    for case in json.loads(result.stdout.strip().splitlines()[-1])['cases']:
        cases.check(case['id'], case['expected'], case['observed'], case['passed'])
    cases.denied('authenticated cannot read the spend ledger',
                 stack.as_role('authenticated', USER_A, 'select * from app_private.model_invocations'), 'permission denied')


def guard_cases(stack: AppStack, cases: Cases, root: Path) -> None:
    stack.sql("update autobots_disposable.marker set run_id = 'something-else';")
    try:
        apply_migrations(stack, root / MIGRATIONS)
        cases.check('a wrong marker refuses migration', 'refused', 'ran', False)
    except Refused as refusal:
        cases.check('a wrong marker refuses migration', 'refused', str(refusal), True)
    stack.sql(f"update autobots_disposable.marker set run_id = '{stack.target.project}';")


def type_cases(stack: AppStack, cases: Cases, root: Path, write: bool) -> None:
    text = row_types(public_columns(stack))
    path = root / ROW_TYPES
    if write:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
    current = path.read_text() if path.is_file() else ''
    cases.check('generated public row types match the schema', 'no drift', 'match' if current == text else 'drift', current == text)
    cases.check('row types hold no private schema', 'public only', 'public only', 'checkpoint_writes' not in text and 'Credentials' not in text)


def qualify(root: Path, write_types: bool = False) -> int:
    project = f'{PROJECT_PREFIX}{secrets.token_hex(4)}'
    gateway_port = free_port()
    db_port = free_port([gateway_port])
    target = Target(project, db_port, gateway_port)
    stack = AppStack(target, root, root / 'infra/supabase/upstream/docker-compose.yml', values=generated_values(gateway_port, db_port))
    stack.migrator_password, stack.runtime_password = secrets.token_hex(24), secrets.token_hex(24)
    require_identity(target, tool_env())
    if run(['docker', 'info', '--format', '{{.ServerVersion}}'], tool_env(), 30).returncode:
        raise Unavailable('the Docker engine is not reachable')
    (root / REPORT).unlink(missing_ok=True)
    rendered = require_rendered(stack)
    require_images({'services': {'db': rendered['services']['db']}})
    cases = Cases()
    before = other_resources(project)
    started_at = time.monotonic()
    try:
        started = stack.compose('up', '-d', '--wait', '--wait-timeout', '120', 'db')
        if started.returncode:
            raise Unavailable(f'the disposable database did not start: {started.stderr[-300:]}')
        bootstrap(stack, root)
        migration_cases(stack, cases, root)
        seed_cases(stack, cases, root)
        constraint_cases(stack, cases)
        access_cases(stack, cases)
        authority_cases(stack, cases)
        framework_cases(stack, cases, root, db_port)
        credential_cases(stack, cases, root, db_port)
        admission_cases(stack, cases, root, db_port)
        guard_cases(stack, cases, root)
        type_cases(stack, cases, root, write_types)
        static_cases(cases, root)
    finally:
        remove_stack(stack)
    label = f'label=com.docker.compose.project={project}'
    left = (run(['docker', 'volume', 'ls', '--filter', label, '--format', '{{.Name}}'], tool_env()).stdout
            + run(['docker', 'ps', '-a', '--filter', label, '--format', '{{.Names}}'], tool_env()).stdout).strip()
    cases.check('cleanup removed the owned containers and volumes', 'none left', left or 'none', not left)
    after = other_resources(project)
    cases.check('other Docker resources are untouched', 'same', f'{len(before)} before, {len(after)} after', before == after)
    passed = all(record['status'] == 'passed' for record in cases.records)
    path = root / REPORT
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps({'schema_version': 'autobots.app-db-qualification/v1', 'completed_at_utc': datetime.now(timezone.utc).isoformat(),
                                'duration_seconds': round(time.monotonic() - started_at, 1), 'input_fingerprint': fingerprint(root),
                                'status': 'passed' if passed else 'failed', 'target_class': 'disposable', 'project': project, 'cases': cases.records,
                                'not_established': ['H1', 'product acceptance', 'the persistent database', 'Storage authorization']}, indent=2) + '\n')
    return 0 if passed else 1


def main(argv: Sequence[str] | None = None) -> int:
    arguments = list(sys.argv[1:] if argv is None else argv)
    if arguments not in (['qualify'], ['types']):
        print('usage: app_db.py qualify|types', file=sys.stderr)
        return 2
    try:
        return qualify(project_root(), write_types=arguments == ['types'])
    except Refused as refusal:
        print(f'REFUSED before any change: {refusal}', file=sys.stderr)
        return 1
    except Unavailable as error:
        print(f'ERROR: {error}', file=sys.stderr)
        return 2


if __name__ == '__main__':
    raise SystemExit(main())
