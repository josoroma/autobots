def access_cases(stack: AppStack, cases: Cases) -> None:
    denied = 'permission denied'
    cases.denied('anonymous cannot read runs', stack.as_role('anon', None, 'select * from public.runs'), denied)
    cases.denied('anonymous cannot read private schema', stack.as_role('anon', None, 'select * from app_private.nothing'), denied)
    cases.denied('authenticated cannot read lease columns',
                 stack.as_role('authenticated', USER_A, 'select lease_generation from public.runs'), denied)
    cases.denied('authenticated cannot read the checkpoint thread',
                 stack.as_role('authenticated', USER_A, 'select checkpoint_thread_id from public.runs'), denied)
    cases.denied('authenticated cannot read the checkpoint schema',
                 stack.as_role('authenticated', USER_A, 'select * from agent_runtime.anything'), denied)
    # R-17: the runtime role deletes only workflow drafts. `where false` keeps a failed case harmless.
    cases.denied('the runtime role cannot delete a run', stack.runtime('delete from public.runs where false;\n'), denied)
    cases.denied('the runtime role cannot delete a run event',
                 stack.runtime('delete from public.run_events where false;\n'), denied)
    deletable = rows(stack, held_privileges('autobots_runtime', APP_SCHEMAS, ('DELETE', 'TRUNCATE')))
    cases.check('the catalog grants the runtime role DELETE on workflow drafts only', 'public.workflow_drafts:DELETE', deletable,
                deletable == 'public.workflow_drafts:DELETE')
    # R-17: the RLS and grant conventions of every table, from the catalog, beside the per-case denials above.
    unguarded = rows(stack, "select coalesce(string_agg(c.relname, ',' order by c.relname), '') from pg_class c "
                            "join pg_namespace n on n.oid = c.relnamespace where n.nspname = 'public' "
                            "and c.relkind in ('r', 'p') and not c.relrowsecurity;")
    cases.check('every public table enables row level security', 'none without it', unguarded or 'none', unguarded == '')
    anonymous = rows(stack, held_privileges('anon', APP_SCHEMAS, EVERY_PRIVILEGE))
    cases.check('anonymous holds no privilege on any app table', 'none', anonymous or 'none', anonymous == '')
    private = rows(stack, held_privileges('authenticated', APP_SCHEMAS[1:], EVERY_PRIVILEGE))
    usage = rows(stack, "select bool_or(has_schema_privilege(r, s, 'USAGE')) from unnest(array['anon', 'authenticated']) r, "
                        "unnest(array['app_private', 'agent_runtime']) s;")
    cases.check('authenticated holds nothing in the private and checkpoint schemas', 'no table privilege, no schema usage',
                (private or 'none', usage), private == '' and usage == 'f')
    writes = rows(stack, held_privileges('authenticated', ('public',), WRITE_PRIVILEGES))
    expected_writes = 'public.user_profiles:INSERT,UPDATE;public.workflow_drafts:DELETE,INSERT,UPDATE'
    cases.check('authenticated writes only its profile and workflow drafts', expected_writes, writes, writes == expected_writes)
    cases.denied('authenticated cannot write runs',
                 stack.as_role('authenticated', USER_A, f"update public.runs set status = 'failed' where id = '{RUN_A}'"), denied)
    own = last_line(stack.as_role('authenticated', USER_A, 'select count(id) from public.runs'))
    cases.check('a member reads its workspace runs', '1', own, own == '1')
    other = last_line(stack.as_role('authenticated', USER_B, f"select count(id) from public.runs where id = '{RUN_A}'"))
    cases.check('another workspace reads no run', '0', other, other == '0')


