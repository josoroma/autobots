def type_cases(stack: AppStack, cases: Cases, root: Path, write: bool, snapshot: str) -> None:
    """The two generated views of the schema: the exposure row types (Decision 0029 F6, SQLI-06) and the
    snapshot for readers (SQLI-09). `types` writes them; otherwise any difference is drift."""
    text = row_types(exposed_columns(stack))
    for path, generated in ((root / ROW_TYPES, text), (root / SCHEMA_SNAPSHOT, snapshot)):
        if write:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(generated)
    current = (root / ROW_TYPES).read_text() if (root / ROW_TYPES).is_file() else ''
    cases.check('generated row types match the columns authenticated can select', 'no drift', 'match' if current == text else 'drift', current == text)
    cases.check('row types hold no private schema', 'public only', 'public only', 'checkpoint_writes' not in text and 'Credentials' not in text)
    withheld = [column for column in ('lease_generation', 'checkpoint_thread_id', 'policy_snapshot', 'consumed_at') if f'  {column}:' in text]
    cases.check('row types hold no column authenticated cannot select', 'none of the withheld run and approval columns', withheld or 'none', not withheld)
    stored = (root / SCHEMA_SNAPSHOT).read_text() if (root / SCHEMA_SNAPSHOT).is_file() else ''
    cases.check('the schema snapshot matches the migrations and bootstrap files', 'no drift', 'match' if stored == snapshot else 'drift',
                stored == snapshot and snapshot.startswith(SNAPSHOT_HEADER) and 'CREATE TABLE public.runs' in snapshot)


def qualify(root: Path, write_types: bool = False) -> int:
    cases = Cases(model_transport=MODEL_TRANSPORT)
    with app_project(root, cases, report=root / REPORT, services=SERVICES) as app:
        stack, db_port = app.stack, app.db_port
        started = stack.compose('up', '-d', '--wait', '--wait-timeout', '240', *SERVICES, timeout=300)
        if started.returncode:
            raise Unavailable(f'the disposable database and Storage did not start: {started.stderr[-300:]}')
        bootstrap(stack, root)
        migration_cases(stack, cases, root)
        seed_cases(stack, cases, root)
        storage_cases(stack, cases, root)
        # Before the framework cases grant CREATE on agent_runtime and run the framework's setup, which the install never does.
        snapshot = schema_snapshot(stack)
        constraint_cases(stack, cases)
        version_cases(stack, cases)
        lookup_cases(stack, cases)
        access_cases(stack, cases)
        profile_cases(stack, cases)
        draft_cases(stack, cases)
        authority_cases(stack, cases)
        framework_cases(stack, cases, root, db_port)
        credential_cases(stack, cases, root, db_port)
        admission_cases(stack, cases, root, db_port)
        run_cases(stack, cases, root, db_port)
        worker_cases(stack, cases, root, db_port)
        tool_cases(stack, cases, root, db_port)
        loop_cases(stack, cases, root, db_port)
        recovery_cases(stack, cases, root, db_port)
        expert_cases(stack, cases, root, db_port)
        workflow_cases(stack, cases, root, db_port)
        routine_cases(stack, cases, root, db_port)
        memory_cases(stack, cases, root, db_port)
        improvement_cases(stack, cases, root, db_port)
        guard_cases(stack, cases, root)
        type_cases(stack, cases, root, write_types, snapshot)
        static_cases(cases, root)
    return finish(root, root / REPORT, 'autobots.app-db-qualification/v1', cases, app.started_at,
                  ['H1', 'product acceptance', 'the persistent database', 'Storage authorization through the Storage API'],
                  project=stack.target.project)


def main(argv: Sequence[str] | None = None) -> int:
    arguments = list(sys.argv[1:] if argv is None else argv)
    if arguments not in (['qualify'], ['types']):
        print('usage: app_db.py qualify|types', file=sys.stderr)
        return 2
    try:
        return qualify(project_root(), write_types=arguments == ['types'])
    except Refused as refusal:
        print(f'REFUSED before any change: {refusal}', file=sys.stderr)
        return 1
    except Unavailable as error:
        print(f'ERROR: {error}', file=sys.stderr)
        return 2


if __name__ == '__main__':
    raise SystemExit(main())
