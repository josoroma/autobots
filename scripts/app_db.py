    put = stack.as_role('authenticated', USER_A, f"insert into storage.objects (bucket_id, name) values ('workspace-artifacts', '{folder}/mine.txt')")
    cases.check("a member can't add an object to its own workspace", 'refused by row-level security', (put.stderr or put.stdout).strip()[-120:],
                put.returncode != 0 and 'row-level security' in put.stderr)
